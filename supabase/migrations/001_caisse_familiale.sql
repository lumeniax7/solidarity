create extension if not exists pgcrypto;

create table if not exists public.users (
  id uuid primary key references auth.users(id) on delete cascade,
  open_id text unique not null,
  name text,
  email text,
  login_method text default 'supabase' not null,
  role text default 'user' not null check (role in ('user', 'admin')),
  created_at timestamptz default now() not null,
  updated_at timestamptz default now() not null,
  last_signed_in timestamptz default now() not null
);

create table if not exists public.members (
  id bigint generated by default as identity primary key,
  full_name varchar(160) not null,
  phone varchar(40),
  email varchar(320),
  joined_at timestamptz default now() not null,
  is_active boolean default true not null,
  notes text,
  created_at timestamptz default now() not null,
  updated_at timestamptz default now() not null
);

create table if not exists public.payment_transactions (
  id bigint generated by default as identity primary key,
  member_id bigint not null references public.members(id) on delete restrict,
  payment_date timestamptz not null,
  amount integer not null check (amount > 0),
  payment_method varchar(40) default 'ESPECES' not null,
  reference varchar(120),
  observation text,
  recorded_by uuid not null references public.users(id) on delete restrict,
  created_at timestamptz default now() not null
);

create table if not exists public.payment_allocations (
  id bigint generated by default as identity primary key,
  payment_transaction_id bigint not null references public.payment_transactions(id) on delete cascade,
  member_id bigint not null references public.members(id) on delete restrict,
  month_key varchar(7) not null check (month_key ~ '^[0-9]{4}-[0-9]{2}$'),
  amount integer not null check (amount > 0),
  created_at timestamptz default now() not null,
  unique (payment_transaction_id, month_key)
);

create table if not exists public.cash_transactions (
  id bigint generated by default as identity primary key,
  direction text not null check (direction in ('IN', 'OUT')),
  source_type varchar(40) not null,
  source_id bigint,
  amount integer not null check (amount > 0),
  transaction_date timestamptz not null,
  description text,
  created_by uuid not null references public.users(id) on delete restrict,
  created_at timestamptz default now() not null
);

create table if not exists public.withdrawals (
  id bigint generated by default as identity primary key,
  withdrawal_date timestamptz not null,
  amount integer not null check (amount > 0),
  category text not null check (category in ('SANTE','URGENCE','DECES','EDUCATION','EVENEMENT_FAMILIAL','AIDE_FAMILIALE','DEPLACEMENT','AUTRE')),
  beneficiary varchar(160),
  motif varchar(255) not null,
  description text,
  payment_method varchar(40) default 'ESPECES' not null,
  reference varchar(120),
  observation text,
  created_by uuid not null references public.users(id) on delete restrict,
  created_at timestamptz default now() not null
);

create table if not exists public.announcements (
  id bigint generated by default as identity primary key,
  title varchar(180) not null,
  body text not null,
  created_by uuid not null references public.users(id) on delete restrict,
  published_at timestamptz default now() not null
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(id) on delete cascade,
  title varchar(180) not null,
  body text not null,
  read_at timestamptz,
  created_at timestamptz default now() not null
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  action varchar(40) not null,
  entity_type varchar(80) not null,
  entity_id bigint,
  old_value jsonb,
  new_value jsonb,
  user_id uuid references public.users(id) on delete set null,
  created_at timestamptz default now() not null
