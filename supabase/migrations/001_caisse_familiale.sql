create or replace function public.allocate_payment(
  p_member_id bigint,
  p_amount integer,
  p_payment_date timestamptz,
  p_payment_method varchar default 'ESPECES',
  p_reference varchar default null,
  p_observation text default null,
  p_forced_month varchar default null
)
returns jsonb
language plpgsql
security invoker
set search_path = public
as $$
declare
  member_row public.members%rowtype;
  payment_id bigint;
  remaining integer := p_amount;
  contribution integer := public.monthly_contribution();
  key varchar(7);
  paid integer;
  applied integer;
  allocation_json jsonb := '[]'::jsonb;
  current_month varchar(7) := public.month_key(p_payment_date);
  actor uuid := auth.uid();
begin
  if actor is null then raise exception 'Utilisateur non authentifié'; end if;
  if not public.current_user_is_admin() then raise exception 'Droits administrateur requis'; end if;
  if p_amount is null or p_amount <= 0 then raise exception 'Le montant doit être positif'; end if;
  select * into member_row from public.members where id = p_member_id and is_active = true;
  if not found then raise exception 'Membre introuvable ou inactif'; end if;

  insert into public.payment_transactions(member_id, payment_date, amount, payment_method, reference, observation, recorded_by)
  values (p_member_id, p_payment_date, p_amount, p_payment_method, p_reference, p_observation, actor)
  returning id into payment_id;

  if p_forced_month is not null then
    key := p_forced_month;
    select coalesce(sum(amount), 0) into paid from public.payment_allocations where member_id = p_member_id and month_key = key;
    if paid > 0 then raise exception 'Cette échéance possède déjà un paiement'; end if;
    applied := least(contribution, remaining);
    insert into public.payment_allocations(payment_transaction_id, member_id, month_key, amount) values (payment_id, p_member_id, key, applied);
    allocation_json := allocation_json || jsonb_build_array(jsonb_build_object('monthKey', key, 'amount', applied));
    remaining := remaining - applied;
  else
    for key in select to_char((date_trunc('month', member_row.joined_at at time zone 'UTC') + (n || ' months')::interval)::date, 'YYYY-MM') from generate_series(0, 239) n where to_char((date_trunc('month', member_row.joined_at at time zone 'UTC') + (n || ' months')::interval)::date, 'YYYY-MM') <= current_month
      union all
      select public.add_months(current_month, n) from generate_series(1, 120) n
    loop
      exit when remaining <= 0;
      select coalesce(sum(amount), 0) into paid from public.payment_allocations where member_id = p_member_id and month_key = key;
      applied := least(greatest(contribution - paid, 0), remaining);
      if applied > 0 then
        insert into public.payment_allocations(payment_transaction_id, member_id, month_key, amount) values (payment_id, p_member_id, key, applied);
        allocation_json := allocation_json || jsonb_build_array(jsonb_build_object('monthKey', key, 'amount', applied));
        remaining := remaining - applied;
      end if;
    end loop;
  end if;

  if remaining > 0 then raise exception 'Impossible d’affecter le montant aux échéances disponibles'; end if;
  insert into public.cash_transactions(direction, source_type, source_id, amount, transaction_date, description, created_by)
  values ('IN', 'PAYMENT', payment_id, p_amount, p_payment_date, 'Cotisation de ' || member_row.full_name, actor);
  return jsonb_build_object('paymentId', payment_id, 'memberName', member_row.full_name, 'allocation', allocation_json);
end;
$$;

create or replace function public.create_withdrawal(
  p_withdrawal_date timestamptz,
  p_amount integer,
  p_category text,
  p_motif varchar,
  p_beneficiary varchar default null,
  p_description text default null,
  p_payment_method varchar default 'ESPECES',
  p_reference varchar default null,
  p_observation text default null
)
returns bigint
language plpgsql
security invoker
set search_path = public
as $$
declare
  actor uuid := auth.uid();
  withdrawal_id bigint;
  available integer;
begin
  if actor is null or not public.current_user_is_admin() then raise exception 'Droits administrateur requis'; end if;
  select coalesce(sum(case when direction = 'IN' then amount else -amount end), 0) into available from public.cash_transactions;
  if p_amount <= 0 or p_amount > available then raise exception 'Solde insuffisant ou montant invalide'; end if;
  insert into public.withdrawals(withdrawal_date, amount, category, beneficiary, motif, description, payment_method, reference, observation, created_by)
  values (p_withdrawal_date, p_amount, p_category, p_beneficiary, p_motif, p_description, p_payment_method, p_reference, p_observation, actor)
  returning id into withdrawal_id;
  insert into public.cash_transactions(direction, source_type, source_id, amount, transaction_date, description, created_by)
  values ('OUT', 'WITHDRAWAL', withdrawal_id, p_amount, p_withdrawal_date, p_motif, actor);
  return withdrawal_id;
end;
$$;

create or replace view public.member_situations as
with contribution as (select public.monthly_contribution() as amount),
paid as (select member_id, month_key, sum(amount)::integer as amount from public.payment_allocations group by member_id, month_key),
months as (
  select m.id as member_id, m.full_name, m.phone, m.email, m.joined_at, m.is_active, c.amount as contribution,
    to_char(gs.month_start::date, 'YYYY-MM') as month_key
  from public.members m cross join contribution c
  cross join lateral generate_series(date_trunc('month', m.joined_at), date_trunc('month', now()), interval '1 month') gs(month_start)
),
current_due as (
  select months.member_id, months.full_name, months.phone, months.email, months.joined_at, months.is_active, months.contribution,
    sum(greatest(months.contribution - coalesce(paid.amount, 0), 0))::integer as due_amount,
    sum(coalesce(paid.amount, 0))::integer as paid_amount,
    count(*) filter (where coalesce(paid.amount, 0) >= months.contribution)::integer as paid_months,
    count(*) filter (where coalesce(paid.amount, 0) > 0 and coalesce(paid.amount, 0) < months.contribution)::integer as partial_months,
    count(*) filter (where coalesce(paid.amount, 0) < months.contribution)::integer as late_months
  from months left join paid on paid.member_id = months.member_id and paid.month_key = months.month_key
  group by months.member_id, months.full_name, months.phone, months.email, months.joined_at, months.is_active, months.contribution
), advances as (
  select p.member_id, count(*)::integer as advance_months, max(p.month_key) as up_to_month
  from paid p where p.month_key > public.month_key(now()) and p.amount >= public.monthly_contribution() group by p.member_id
)
select d.*, coalesce(a.advance_months, 0) as advance_months, a.up_to_month,
  case when d.due_amount > 0 then 'RETARD' when coalesce(a.advance_months, 0) > 0 then 'AVANCE' else 'A_JOUR' end as status
from current_due d left join advances a using (member_id);

create or replace view public.family_summary as
select
  (select count(*) from public.members)::integer as total_members,
  (select count(*) from public.members where is_active)::integer as active_members,
  (select coalesce(sum(amount), 0) from public.cash_transactions where direction = 'IN')::integer as total_in,
  (select coalesce(sum(amount), 0) from public.cash_transactions where direction = 'OUT')::integer as total_out,
  (select coalesce(sum(amount), 0) from public.cash_transactions where direction = 'IN')::integer - (select coalesce(sum(amount), 0) from public.cash_transactions where direction = 'OUT')::integer as balance,
  (select coalesce(sum(due_amount), 0) from public.member_situations where is_active)::integer as arrears,
  (select count(*) from public.member_situations where status = 'RETARD' and is_active)::integer as late_members,
  (select count(*) from public.member_situations where status = 'A_JOUR' and is_active)::integer as up_to_date_members,
  (select count(*) from public.member_situations where status = 'AVANCE' and is_active)::integer as members_with_advance;

