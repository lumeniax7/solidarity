create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.users (id, open_id, name, email, login_method, role)
  values (
    new.id,
    new.id::text,
    coalesce(new.raw_user_meta_data ->> 'full_name', new.email),
    new.email,
    'supabase',
    case when coalesce(new.raw_user_meta_data ->> 'role', '') = 'admin' or new.email = 'admin@tontine.local' then 'admin' else 'user' end
  )
  on conflict (id) do update set
    name = excluded.name,
    email = excluded.email,
    last_signed_in = now();
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert or update on auth.users for each row execute function public.handle_new_auth_user();

create or replace function public.current_user_is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.users where id = auth.uid() and role = 'admin')
      or coalesce((auth.jwt() -> 'user_metadata' ->> 'role') = 'admin', false);
$$;

create or replace function public.monthly_contribution()
returns integer
language sql
stable
security invoker
as $$
  select coalesce((select setting_value::integer from public.settings where setting_key = 'monthly_contribution'), 1000);
$$;

create or replace function public.month_key(value timestamptz)
returns varchar(7)
language sql
immutable
as $$ select to_char(value at time zone 'UTC', 'YYYY-MM'); $$;

create or replace function public.add_months(key varchar(7), amount integer)
returns varchar(7)
language sql
immutable
as $$ select to_char((to_date(key || '-01', 'YYYY-MM-DD') + make_interval(months => amount))::date, 'YYYY-MM'); $$;

create or replace function public.audit_row_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  entity_id_value bigint;
begin
  if tg_table_name = 'settings' then
    entity_id_value := null;
  elsif tg_op = 'DELETE' then
    entity_id_value := old.id;
  else
    entity_id_value := new.id;
  end if;
  insert into public.audit_logs(action, entity_type, entity_id, old_value, new_value, user_id)
  values (
    tg_op,
    tg_table_name,
    entity_id_value,
    case when tg_op in ('UPDATE','DELETE') then to_jsonb(old) else null end,
    case when tg_op in ('INSERT','UPDATE') then to_jsonb(new) else null end,
    auth.uid()
  );
  return case when tg_op = 'DELETE' then old else new end;
end;
$$;

